export function DotIcon({
  name,
  size = 24,
  className,
}: {
  name: keyof typeof G
  size?: number
  className?: string
}) {
  const rows = G[name] || []
  return (
    <span
      className={clsx('gico', className)}
      style={{ ['--gs' as string]: `${size}px` }}
      aria-hidden="true"
    >
      {rows.map((row, y) =>
        [...row].map((c, x) => <i key={`${y}-${x}`} className={c === '#' ? 'on' : undefined} />),
      )}
    </span>
  )
}
